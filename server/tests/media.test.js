import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { app, bearer, request, signUp, useDatabase } from './helpers/app.js';
import { api, files } from './helpers/content.js';
import { detectFileType, sanitizeDisplayName } from '../src/lib/fileType.js';
import { createCloudinaryProvider } from '../src/integrations/storage/cloudinary.provider.js';
import { setStorage } from '../src/integrations/storage/index.js';
import { MediaAsset } from '../src/modules/media/media-asset.model.js';

useDatabase();

const UPLOAD_DIR = process.env.UPLOAD_DIR;
const filesOnDisk = () => (fs.existsSync(UPLOAD_DIR) ? fs.readdirSync(UPLOAD_DIR, { recursive: true, withFileTypes: true }).filter((e) => e.isFile()) : []);
const tmpLeftovers = () => {
  const dir = path.join(path.dirname(UPLOAD_DIR), 'cms-uploads');
  return fs.existsSync(dir) ? fs.readdirSync(dir).length : 0;
};

describe('file type detection (from the bytes, not the name)', () => {
  test('recognises every allowed format', () => {
    const expect = { png: 'image/png', jpg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp', pdf: 'application/pdf', mp4: 'video/mp4', mov: 'video/quicktime', webm: 'video/webm' };
    for (const [name, mime] of Object.entries(expect)) assert.equal(detectFileType(files[name]()).mime, mime, name);
  });

  test('rejects scripts, markup, executables, archives, HEIC and truncated data', () => {
    for (const name of ['exe', 'html', 'svg', 'text', 'heic', 'zip']) assert.equal(detectFileType(files[name]()), null, name);
    assert.equal(detectFileType(Buffer.alloc(0)), null);
    assert.equal(detectFileType(Buffer.from([0x89, 0x50])), null);
    assert.equal(detectFileType('not a buffer'), null);
  });

  test('display names are sanitised and never contain a path', () => {
    assert.equal(sanitizeDisplayName('../../etc/passwd'), 'passwd');
    assert.equal(sanitizeDisplayName('C:\\Users\\me\\evil.png'), 'evil.png');
    assert.equal(sanitizeDisplayName('a\u0000b\nc<d>.png'), 'abcd.png');
    assert.equal(sanitizeDisplayName(''), 'file');
    assert.ok(sanitizeDisplayName('x'.repeat(500)).length <= 120);
  });
});

describe('uploading', () => {
  test('stores a valid file, returns safe metadata, and the bytes on disk are exactly what was sent', async () => {
    const { token, user } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const png = files.png(1234);
    const res = await api.upload(token, id, png, 'Beach day.PNG');
    assert.equal(res.status, 201);
    const a = res.body.data;
    assert.deepEqual([a.resourceType, a.mimeType, a.bytes, a.name, a.contentId], ['image', 'image/png', 1234, 'Beach day.PNG', id]);
    const text = JSON.stringify(res.body);
    for (const leak of ['storageKey', 'provider', 'owner', UPLOAD_DIR, user.id]) assert.ok(!text.includes(leak), `must not expose ${leak}`);

    const stored = await MediaAsset.findById(a.id);
    const onDisk = path.join(UPLOAD_DIR, stored.storageKey);
    assert.ok(fs.readFileSync(onDisk).equals(png));
    // the stored name is generated by the server, under the owner's folder, with an extension from the DETECTED type
    assert.match(stored.storageKey, new RegExp(`^${user.id}/[0-9a-f]{32}\\.png$`));
    assert.ok(!stored.storageKey.includes('Beach'));
    assert.equal(tmpLeftovers(), 0, 'temporary upload files must be cleaned up');
    assert.equal((await api.get(token, id)).body.data.assets.length, 1);
  });

  test('the real type wins over the declared name and Content-Type', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const jpgNamedPng = await api.upload(token, id, files.jpg(), 'photo.png');
    assert.equal(jpgNamedPng.body.data.mimeType, 'image/jpeg');
    const stored = await MediaAsset.findById(jpgNamedPng.body.data.id);
    assert.ok(stored.storageKey.endsWith('.jpg'));
  });

  test('accepts each allowed type', async () => {
    const { token } = await signUp();
    for (const [name, resourceType] of [['gif', 'image'], ['webp', 'image'], ['pdf', 'document'], ['mp4', 'video'], ['mov', 'video'], ['webm', 'video']]) {
      const id = (await api.create(token, { title: name })).body.data.id;
      const res = await api.upload(token, id, files[name](), `x.${name}`);
      assert.equal(res.status, 201, name);
      assert.equal(res.body.data.resourceType, resourceType, name);
    }
  });

  test('rejects disguised or dangerous files with 415 and stores nothing', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    for (const [kind, name] of [['exe', 'holiday.png'], ['html', 'page.png'], ['svg', 'logo.svg'], ['svg', 'logo.png'], ['text', 'notes.jpg'], ['zip', 'video.mp4'], ['heic', 'photo.heic']]) {
      const res = await api.upload(token, id, files[kind](), name);
      assert.equal(res.status, 415, `${kind} as ${name}`);
      assert.equal(res.body.error.code, 'UNSUPPORTED_FILE_TYPE');
    }
    assert.equal(await MediaAsset.countDocuments(), 0);
    assert.equal(filesOnDisk().length, 0);
    assert.equal(tmpLeftovers(), 0);
  });

  test('enforces a size limit per type (images 10 KB, documents 20 KB, video 50 KB in this test setup)', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const bigImage = await api.upload(token, id, files.png(11_000), 'big.png');
    assert.equal(bigImage.status, 413);
    assert.equal(bigImage.body.error.code, 'FILE_TOO_LARGE');
    assert.match(bigImage.body.error.message, /Images/);
    assert.equal((await api.upload(token, id, files.pdf(21_000), 'big.pdf')).status, 413);
    assert.equal((await api.upload(token, id, files.png(9_000), 'ok.png')).status, 201); // under the image limit
    assert.equal((await api.upload(token, id, files.mp4(40_000), 'ok.mp4')).status, 201); // video limit is larger
    assert.equal(await MediaAsset.countDocuments(), 2);
  });

  test('a file over the hard streaming cap is cut off with 413 and leaves no temp file', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const res = await api.upload(token, id, files.mp4(200_000), 'huge.mp4');
    assert.equal(res.status, 413);
    assert.equal(res.body.error.code, 'FILE_TOO_LARGE');
    assert.equal(tmpLeftovers(), 0);
    assert.equal(filesOnDisk().length, 0);
  });

  test('rejects missing, empty, wrongly-named and multiple files', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const none = await request(app).post(`/api/v1/content/${id}/assets`).set(bearer(token)).send({});
    assert.equal(none.status, 400);
    assert.equal(none.body.error.code, 'NO_FILE');
    assert.equal((await api.upload(token, id, Buffer.alloc(0), 'empty.png')).status, 400);
    assert.equal((await api.upload(token, id, files.png(), 'a.png', 'avatar')).status, 400); // wrong field name
    const two = await request(app).post(`/api/v1/content/${id}/assets`).set(bearer(token)).attach('file', files.png(), 'a.png').attach('file', files.png(), 'b.png');
    assert.equal(two.status, 400);
    assert.equal(await MediaAsset.countDocuments(), 0);
  });

  test('limits the number of files per content item', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    for (let i = 0; i < 3; i++) assert.equal((await api.upload(token, id, files.png(), `${i}.png`)).status, 201);
    const res = await api.upload(token, id, files.png(), 'fourth.png');
    assert.equal(res.status, 409);
    assert.equal(res.body.error.code, 'TOO_MANY_ASSETS');
    // other content items have their own budget
    const other = (await api.create(token, { title: 'other' })).body.data.id;
    assert.equal((await api.upload(token, other, files.png(), 'x.png')).status, 201);
  });

  test('hostile file names cannot escape the upload folder', async () => {
    const { token, user } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const res = await api.upload(token, id, files.png(), '../../../../evil.png');
    assert.equal(res.status, 201);
    assert.equal(res.body.data.name, 'evil.png');
    const all = filesOnDisk();
    assert.equal(all.length, 1);
    assert.ok(path.resolve(all[0].parentPath ?? all[0].path).startsWith(path.resolve(UPLOAD_DIR, user.id)));
    assert.ok(!fs.existsSync(path.resolve(UPLOAD_DIR, '..', 'evil.png')));
  });

  test('uploads are refused on archived content', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    await api.archive(token, id);
    assert.equal((await api.upload(token, id, files.png())).status, 409);
  });

  test('a foreign or unknown content id is rejected BEFORE any file is written', async () => {
    const a = await signUp();
    const b = await signUp();
    const id = (await api.create(a.token)).body.data.id;
    assert.equal((await api.upload(b.token, id, files.png())).status, 404);
    assert.equal((await api.upload(b.token, '507f1f77bcf86cd799439011', files.png())).status, 404);
    assert.equal((await api.upload(b.token, 'not-an-id', files.png())).status, 404);
    assert.equal(filesOnDisk().length, 0);
    assert.equal(tmpLeftovers(), 0);
  });
});

describe('serving and removing files', () => {
  test('serves the exact bytes with the detected type, and supports range requests for video', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const video = files.mp4(5000);
    const asset = (await api.upload(token, id, video, 'clip.mp4')).body.data;
    const url = `/api/v1${(await api.access(token, asset.id)).body.path}`;

    const full = await request(app).get(url).buffer(true).parse((res, cb) => {
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => cb(null, Buffer.concat(chunks)));
    });
    assert.equal(full.status, 200);
    assert.equal(full.headers['content-type'], 'video/mp4');
    assert.ok(full.body.equals(video));
    assert.equal(full.headers['accept-ranges'], 'bytes');

    const part = await request(app).get(url).set('Range', 'bytes=0-99');
    assert.equal(part.status, 206);
    assert.equal(part.headers['content-range'], 'bytes 0-99/5000');
  });

  test('deleting an asset removes the file from disk and the record, and is recorded in history', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const asset = (await api.upload(token, id, files.png(), 'gone.png')).body.data;
    assert.equal(filesOnDisk().length, 1);
    assert.equal((await api.removeAsset(token, id, asset.id)).status, 204);
    assert.equal(filesOnDisk().length, 0);
    assert.equal(await MediaAsset.countDocuments(), 0);
    assert.equal((await api.removeAsset(token, id, asset.id)).status, 404);
    assert.equal((await api.get(token, id)).body.data.assets.length, 0);
  });

  test('an asset can only be removed through the content it belongs to', async () => {
    const { token } = await signUp();
    const c1 = (await api.create(token, { title: 'one' })).body.data.id;
    const c2 = (await api.create(token, { title: 'two' })).body.data.id;
    const asset = (await api.upload(token, c1, files.png())).body.data;
    assert.equal((await api.removeAsset(token, c2, asset.id)).status, 404);
    assert.equal(await MediaAsset.countDocuments(), 1);
  });
});

describe('storage providers', () => {
  const fakeCloudinary = () => {
    const calls = { upload: [], destroy: [], url: [] };
    return {
      calls,
      uploader: {
        upload: async (file, opts) => (calls.upload.push({ file, opts }), { public_id: `${opts.folder}/abc123` }),
        destroy: async (id, opts) => (calls.destroy.push({ id, opts }), { result: 'ok' }),
      },
      url: (id, opts) => (calls.url.push({ id, opts }), `https://res.cloudinary.example/signed/${id}`),
    };
  };

  test('Cloudinary adapter: uploads server-side as private resources in a per-user folder, serves via a signed URL, and cleans up', async () => {
    const fake = fakeCloudinary();
    setStorage({ ...createCloudinaryProvider({ cloudinary: fake }) });
    try {
      const { token, user } = await signUp();
      const id = (await api.create(token)).body.data.id;
      const asset = (await api.upload(token, id, files.png(), 'a.png')).body.data;

      assert.equal(fake.calls.upload.length, 1);
      const { opts } = fake.calls.upload[0];
      assert.equal(opts.type, 'authenticated'); // private: not deliverable without a signature
      assert.equal(opts.resource_type, 'image');
      assert.equal(opts.folder, `cms/${user.id}`);
      assert.equal(opts.use_filename, false); // the user's file name is never used
      assert.equal(opts.overwrite, false);
      const stored = await MediaAsset.findById(asset.id);
      assert.deepEqual([stored.provider, stored.storageKey], ['cloudinary', `cms/${user.id}/abc123`]);

      const served = await request(app).get(`/api/v1/media/${asset.id}/file`).set(bearer(token)).redirects(0);
      assert.equal(served.status, 302);
      assert.equal(served.headers.location, `https://res.cloudinary.example/signed/cms/${user.id}/abc123`);
      assert.deepEqual([fake.calls.url[0].opts.type, fake.calls.url[0].opts.sign_url], ['authenticated', true]);

      // the redirect is only reachable through authorisation
      const other = await signUp();
      assert.equal((await request(app).get(`/api/v1/media/${asset.id}/file`).set(bearer(other.token))).status, 404);
      assert.equal((await request(app).get(`/api/v1/media/${asset.id}/file`)).status, 401);

      assert.equal((await api.removeAsset(token, id, asset.id)).status, 204);
      assert.deepEqual([fake.calls.destroy[0].opts.type, fake.calls.destroy[0].opts.invalidate], ['authenticated', true]);
    } finally {
      setStorage(undefined);
    }
  });

  test('Cloudinary adapter: PDFs and videos use the right resource types', async () => {
    const fake = fakeCloudinary();
    setStorage({ ...createCloudinaryProvider({ cloudinary: fake }) });
    try {
      const { token } = await signUp();
      const id = (await api.create(token)).body.data.id;
      await api.upload(token, id, files.pdf(), 'doc.pdf');
      await api.upload(token, id, files.mp4(), 'clip.mp4');
      assert.deepEqual(fake.calls.upload.map((c) => c.opts.resource_type), ['image', 'video']); // Cloudinary stores PDFs as "image" resources
    } finally {
      setStorage(undefined);
    }
  });

  test('a storage failure on upload gives 502, stores no record and cleans the temp file', async () => {
    setStorage({ name: 'local', save: async () => { throw new Error('disk on fire'); }, remove: async () => {}, serve: async () => {} });
    try {
      const { token } = await signUp();
      const id = (await api.create(token)).body.data.id;
      const res = await api.upload(token, id, files.png());
      assert.equal(res.status, 502);
      assert.ok(!JSON.stringify(res.body).includes('fire'), 'internal error details must not leak');
      assert.equal(await MediaAsset.countDocuments(), 0);
      assert.equal(tmpLeftovers(), 0);
    } finally {
      setStorage(undefined);
    }
  });

  test('a storage failure on delete keeps the database intact so nothing is orphaned', async () => {
    const { token } = await signUp();
    const id = (await api.create(token)).body.data.id;
    const asset = (await api.upload(token, id, files.png())).body.data;
    setStorage({ name: 'local', remove: async () => { throw new Error('nope'); } });
    try {
      assert.equal((await api.removeAsset(token, id, asset.id)).status, 502);
      assert.equal(await MediaAsset.countDocuments(), 1);
      await api.archive(token, id);
      assert.equal((await api.remove(token, id)).status, 502); // permanent delete is also all-or-nothing
      assert.equal((await api.get(token, id)).status, 200);
    } finally {
      setStorage(undefined);
    }
  });
});
